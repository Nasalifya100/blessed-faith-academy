#!/usr/bin/env node
/**
 * Writes compile-time deployment identity for OpenNext/Workers bundles.
 * NEXT_PUBLIC_* env alone is unreliable on the Worker runtime path.
 *
 * Never writes secrets.
 */
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "src", "lib", "ops", "build-info.generated.ts");

function pick(...names) {
  for (const name of names) {
    const value = process.env[name];
    if (value && String(value).trim()) return String(value).trim();
  }
  return null;
}

const info = {
  applicationVersion: pick("NEXT_PUBLIC_APP_VERSION", "npm_package_version") || "0.1.0",
  gitSha: pick("NEXT_PUBLIC_GIT_SHA", "GITHUB_SHA", "CF_PAGES_COMMIT_SHA") || "unknown",
  buildTimestamp:
    pick("NEXT_PUBLIC_BUILD_TIMESTAMP", "BUILD_TIMESTAMP") ||
    new Date().toISOString(),
  environmentName:
    pick("NEXT_PUBLIC_DEPLOY_ENV", "DEPLOY_ENV") || "local",
  workerName: pick("NEXT_PUBLIC_WORKER_NAME") || "bfa-sms-staging",
};

const source = `/**
 * AUTO-GENERATED by scripts/write-build-info.cjs — do not edit by hand.
 * Safe public deployment identity only (no secrets).
 */
export const BUILD_INFO = ${JSON.stringify(info, null, 2)} as const;
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, source, "utf8");
console.log(
  `Wrote build-info: version=${info.applicationVersion} sha=${info.gitSha.slice(0, 12)} env=${info.environmentName}`,
);
